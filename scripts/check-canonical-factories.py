def require(condition, message):
    if not condition:
        raise ValueError(message)


def boolean_modes(rows, label):
    # Python considers False == 0 == 0.0 and True == 1 == 1.0, including
    # dictionary/set keys. Validate the wire type before indexing build modes.
    require(all(type(row["optimize_lir"]) is bool for row in rows),
            f"{label}: optimize_lir must be a boolean")


def read_source(relative):
    path = (ROOT / relative).resolve(strict=True)
    require(not Path(relative).is_absolute() and path.is_relative_to(ROOT), "Source escapes repository")
    return path.read_bytes()


def serialize(tree):
    if isinstance(tree, tuple):
        return b"\xff" + serialize(tree[0]) + serialize(tree[1])
    require(isinstance(tree, bytes), "Expected raw atom or pair")
    size = len(tree)
    if not size:
        return b"\x80"
    if size == 1 and tree[0] < 128:
        return tree
    for prefix_size in range(1, 6):
        if size < 1 << (7 - prefix_size + 8 * (prefix_size - 1)):
            prefix = ((255 << (8 - prefix_size)) & 255) | (size >> (8 * (prefix_size - 1)))
            return bytes([prefix]) + size.to_bytes(prefix_size, "big")[1:] + tree
    raise ValueError("Atom exceeds the bounded checker codec")


def deserialize(data):
    require(len(data) <= 8_000_000, "Artifact exceeds checker bound")
    cursor = 0

    def read():
        nonlocal cursor
        require(cursor < len(data), "Truncated tree")
        head = data[cursor]
        cursor += 1
        if head == 255:
            return read(), read()
        if head < 128:
            return bytes([head])
        if head == 128:
            return b""
        prefix_size = 0
        while head & (128 >> prefix_size):
            prefix_size += 1
        require(prefix_size <= 5, "Unsupported oversized/backreference atom encoding")
        end = cursor + prefix_size - 1
        require(end <= len(data), "Truncated atom length")
        size = head & ((1 << (7 - prefix_size)) - 1)
        for byte in data[cursor:end]:
            size = (size << 8) | byte
        cursor = end
        end = cursor + size
        require(end <= len(data), "Truncated atom")
        result = data[cursor:end]
        cursor = end
        return result

    tree = read()
    require(cursor == len(data), "Trailing serialized bytes")
    return tree


def tree_hash(tree):
    if isinstance(tree, bytes):
        return hashlib.sha256(b"\x01" + tree).digest()
    return hashlib.sha256(b"\x02" + tree_hash(tree[0]) + tree_hash(tree[1])).digest()


def parse(text):
    """Read this fixture's explicit integer/hex/proper/improper-tree grammar."""
    tokens = re.findall(r"0x[0-9a-fA-F]*|-?[0-9]+|[().]", text)
    require("".join(tokens) == re.sub(r"\s+", "", text), "Unsupported fixture input syntax")
    cursor = 0

    def read():
        nonlocal cursor
        require(cursor < len(tokens), "Missing input tree")
        token = tokens[cursor]
        cursor += 1
        if token == "(":
            items, tail = [], b""
            while cursor < len(tokens) and tokens[cursor] != ")":
                if tokens[cursor] == ".":
                    require(items, "A dotted pair requires a first element")
                    cursor += 1
                    tail = read()
                    break
                items.append(read())
            require(cursor < len(tokens) and tokens[cursor] == ")", "Missing closing parenthesis")
            cursor += 1
            for item in reversed(items):
                tail = item, tail
            return tail
        require(token not in (".", ")"), "Unexpected tree punctuation")
        if token.startswith("0x"):
            return bytes.fromhex(token[2:])
        value = int(token)
        if value == 0:
            return b""
        size = 1
        while not -(1 << (size * 8 - 1)) <= value < (1 << (size * 8 - 1)):
            size += 1
        return value.to_bytes(size, "big", signed=True)

    result = read()
    require(cursor == len(tokens), "Trailing fixture input")
    return result


def expected(environment):
    tree = parse(environment)
    if not isinstance(tree, tuple):
        return {"status": "rejected"}, None
    return {"status": "accepted", "output_hex": serialize((b"\x01", tree[0])).hex()}, serialize(tree[0]).hex()


def curry_program(tree):
    """Independent standard curried form (a (q . module) (c (q . parameter) 1)) as a raw tree."""
    module, (parameter, _) = tree
    return (b"\x02", ((b"\x01", module), ((b"\x04", ((b"\x01", parameter), (b"\x01", b""))), b"")))


def expected_curry(environment):
    tree = parse(environment)
    if isinstance(tree, tuple) and isinstance(tree[1], tuple) and tree[1][1] == b"":
        return {"status": "accepted", "output_hex": serialize(curry_program(tree)).hex()}
    return {"status": "rejected"}


def validate_curry_factory(puzzle, reader):
    """An original standard-curry factory: exact produced programs from this
    independent raw-tree construction, and recorded second-stage applications
    that must equal their recorded independent expectation. No VM is rerun and
    no canonical module identity is claimed."""
    slug = puzzle["slug"]
    manifest = json.loads(reader(f"puzzles/{slug}/puzzle.json"))
    require(manifest["kind"] == "program_factory" and manifest.get("factory_relation") == "standard_curry"
            and manifest.get("environment", "strict") == "strict", f"{slug}: curry factory needs the strict standard-curry contract")
    applications = manifest.get("factory_applications")
    require(type(applications) is list and applications and all(type(item) is str for item in applications)
            and len(set(applications)) == len(applications), f"{slug}: declared applications must be unique strings")
    require(puzzle["validated"] is True and puzzle["kind"] == "program_factory" and puzzle.get("environment", "strict") == "strict"
            and "module_identity" not in puzzle and puzzle["provenance"] == manifest["provenance"]
            and puzzle["provenance"]["classification"] == "original teaching implementation", f"{slug}: curry factory provenance/identity contract changed")
    require(not puzzle["simulator"] and not puzzle["simulator_comparisons"], f"{slug}: factory must not claim direct ledger admission")
    require(reader(f"puzzles/{slug}/reference.clsp").decode() == puzzle["reference"], f"{slug}: Chialisp comparison source changed")
    rue = puzzle["rue"]
    require(reader(rue["path"]).decode() == rue["source"] and hashlib.sha256(reader(rue["path"])).hexdigest() == rue["sha256"], f"{slug}: Rue comparison source changed")
    boolean_modes(puzzle["artifacts"], f"{slug} artifacts")
    artifacts = {(item["backend"], item["optimize_lir"]): item for item in puzzle["artifacts"]}
    require(len(puzzle["artifacts"]) == len(artifacts) == 5 and set(artifacts) == BUILDS, f"{slug}: five compiler artifacts are required")
    for item in artifacts.values():
        program = bytes.fromhex(item["clvm_hex"])
        require(len(program) == item["bytes"] and tree_hash(deserialize(program)).hex() == item["tree_hash"], f"{slug}: artifact size or tree hash disagrees with its program")
    require([(case["label"], case["solution"]) for case in puzzle["cases"]] == [(case["label"], case["solution"]) for case in manifest["cases"]], f"{slug}: named factory vectors changed")
    accepted = {}
    for case in puzzle["cases"]:
        outcome = expected_curry(case["solution"])
        check_native_outcome(case["native"], case["label"])
        require(case["native"] == outcome, f"{slug}: native curried program differs from the independent standard form: {case['label']}")
        boolean_modes(case["runs"], f"{slug} factory executions")
        runs = {(run["backend"], run["optimize_lir"]): run for run in case["runs"]}
        require(len(case["runs"]) == len(runs) == 5 and set(runs) == BUILDS, f"{slug}: incomplete factory executions")
        for run in runs.values():
            check_execution(run["execution"], f"{slug}/{case['label']}")
        require(all(run["execution"]["outcome"] == outcome for run in runs.values()), f"{slug}: recorded VM result differs: {case['label']}")
        if outcome["status"] == "accepted":
            accepted[case["solution"]] = outcome["output_hex"]
    checks = puzzle["factory_checks"]
    boolean_modes(checks, f"{slug} produced-program checks")
    keys = {(row["environment"], row["backend"], row["optimize_lir"]) for row in checks}
    require(len(checks) == len(keys) and keys == {(environment, *build) for environment in accepted for build in BUILDS}, f"{slug}: missing or duplicate produced-program checks")
    application_inputs = {serialize(parse(solution)) for solution in applications}
    for row in checks:
        program = accepted[row["environment"]]
        require(row.get("relation") == "standard_curry" and row["program_hex"] == program and row["expected_output_hex"] == program,
                f"{slug}: produced program bytes changed, normalized or relabeled")
        runs = row["application_runs"]
        require(len(runs) == len(applications) and {serialize(parse(run["solution"])) for run in runs} == application_inputs, f"{slug}: incomplete second-stage application coverage")
        for run in runs:
            execution = run["execution"]
            check_execution(execution, f"{slug} second-stage application")
            require("expected_outcome" in run, f"{slug}: application lacks its independent expectation")
            check_native_outcome(run["expected_outcome"], f"{slug} application expectation")
            require(execution["outcome"] == run["expected_outcome"], f"{slug}: second-stage program differs from the uncurried module expectation")
            if execution["outcome"]["status"] == "accepted":
                require(type(execution["cost"]) is int and execution["cost"] > 0 and execution["error"] is None, f"{slug}: missing actual successful application execution record")
    return len(puzzle["cases"]), len(checks), sum(len(row["application_runs"]) for row in checks)


def validate(report, reader=read_source):
    require(report.get("vm_failure_protocol") == PROTOCOL, "Missing/unsupported VM failure protocol")
    for path, (sha256, blob) in PINS.items():
        data = reader(path)
        require(hashlib.sha256(data).hexdigest() == sha256, f"Pinned SHA-256 changed: {path}")
        require(hashlib.sha1(f"blob {len(data)}\0".encode() + data).hexdigest() == blob, f"Pinned Git blob changed: {path}")
    require(reader("puzzles/p2-conditions/reference.clsp") == reader(SOURCE), "Canonical source was adapted or wrapped")
    require(reader(ARTIFACT).decode().strip() == CANONICAL_HEX, "Published program bytes changed")
    require(tree_hash(deserialize(bytes.fromhex(CANONICAL_HEX))).hex() == CANONICAL_HASH, "Published module tree hash changed")
    manifest = json.loads(reader("puzzles/p2-conditions/puzzle.json"))
    factories = [puzzle for puzzle in report["puzzles"] if puzzle["kind"] == "program_factory"]
    canonical = [factory for factory in factories if "module_identity" in factory]
    curry = [factory for factory in factories if "module_identity" not in factory
             and factory.get("factory_checks") and all(row.get("relation") == "standard_curry" for row in factory["factory_checks"])]
    require([factory["slug"] for factory in canonical] == ["p2-conditions"] and len(canonical) + len(curry) == len(factories),
            "Unknown or missing canonical factory")
    puzzle = canonical[0]
    require(puzzle["validated"] is True and puzzle["environment"] == "raw", "Factory lacks validated raw-environment contract")
    require(puzzle["provenance"] == manifest["provenance"], "Factory provenance changed")
    provenance = puzzle["provenance"]
    require(provenance["classification"] == "canonical_puzzle_port", "Canonical classification changed")
    upstream = provenance["upstream"]
    require(upstream == {
        "repository": REPOSITORY, "revision": PIN,
        "source_path": "puzzles/p2_conditions.clsp", "snapshot": SOURCE,
        "source_sha256": PINS[SOURCE][0], "git_blob_sha1": PINS[SOURCE][1],
    }, "Canonical source metadata/binding changed")
    require(provenance["license"] == {
        "spdx": "Apache-2.0", "source_path": "LICENSE", "snapshot": LICENSE,
        "sha256": PINS[LICENSE][0], "git_blob_sha1": PINS[LICENSE][1],
    }, "Canonical license metadata/binding changed")
    adaptation = provenance["source_adaptation"]
    require(adaptation["kind"] == "none" and adaptation["reference_sha256"] == PINS[SOURCE][0], "Canonical source adaptation claim changed")
    require(provenance["upstream_artifact"] == {
        "path": ARTIFACT,
        "source_url": f"{REPOSITORY}/blob/{PIN}/puzzles/p2_conditions.clsp.hex",
        "source_sha256": PINS[ARTIFACT][0], "git_blob_sha1": PINS[ARTIFACT][1],
        "clvm_hex": CANONICAL_HEX, "bytes": len(bytes.fromhex(CANONICAL_HEX)),
        "tree_hash": CANONICAL_HASH,
    }, "Published artifact metadata/binding changed")
    require(puzzle["reference"].encode() == reader(SOURCE), "Report no longer records exact original source")
    require(not puzzle["simulator"] and not puzzle["simulator_comparisons"], "Factory must not claim direct condition-spend ledger admission")
    rue = puzzle["rue"]
    require(reader(rue["path"]).decode() == rue["source"] and hashlib.sha256(reader(rue["path"])).hexdigest() == rue["sha256"], "Rue comparison source changed")
    boolean_modes(puzzle["artifacts"], "Factory artifacts")
    artifacts = {(item["backend"], item["optimize_lir"]): item for item in puzzle["artifacts"]}
    require(len(puzzle["artifacts"]) == len(artifacts) == 5 and set(artifacts) == BUILDS, "Five compiler artifacts are required")
    for item in artifacts.values():
        program = bytes.fromhex(item["clvm_hex"])
        require(len(program) == item["bytes"] and tree_hash(deserialize(program)).hex() == item["tree_hash"], "Artifact size or tree hash disagrees with its program")
    identity = puzzle["module_identity"]
    require(identity["upstream_hex"] == CANONICAL_HEX and identity["upstream_tree_hash"] == CANONICAL_HASH, "Module identity target changed")
    boolean_modes(identity["comparisons"], "Factory identity comparisons")
    comparisons = {(row["backend"], row["optimize_lir"]): row for row in identity["comparisons"]}
    require(len(identity["comparisons"]) == len(comparisons) == 5 and set(comparisons) == BUILDS, "Incomplete identity comparisons")
    for key, comparison in comparisons.items():
        require(type(comparison["serialized_bytes_equal"]) is bool and type(comparison["tree_hash_equal"]) is bool, "Identity flags must be booleans")
        require(comparison["serialized_bytes_equal"] == (artifacts[key]["clvm_hex"] == CANONICAL_HEX), "Incorrect serialized identity claim")
        require(comparison["tree_hash_equal"] == (artifacts[key]["tree_hash"] == CANONICAL_HASH), "Incorrect module hash claim")
    require(comparisons[("chialisp", True)]["serialized_bytes_equal"], "Independent Chialisp compiler must reproduce the published artifact")
    for backend in ("rust_mir", "rue_source"):
        require(comparisons[(backend, True)]["serialized_bytes_equal"], f"Optimized {backend} must reproduce the published artifact")
    require([(case["label"], case["solution"]) for case in puzzle["cases"]] == [(case["label"], case["solution"]) for case in manifest["cases"]], "Named factory vectors changed")
    accepted = {}
    for case in puzzle["cases"]:
        outcome, payload = expected(case["solution"])
        check_native_outcome(case["native"], case["label"])
        require(case["native"] == outcome, f"Native raw-tree result differs: {case['label']}")
        boolean_modes(case["runs"], "Factory executions")
        runs = {(run["backend"], run["optimize_lir"]): run for run in case["runs"]}
        require(len(case["runs"]) == len(runs) == 5 and set(runs) == BUILDS, "Incomplete factory executions")
        for run in runs.values():
            check_execution(run["execution"], f"factory/{case['label']}")
        require(all(run["execution"]["outcome"] == outcome for run in runs.values()), f"Recorded VM result differs: {case['label']}")
        if payload is not None:
            accepted[case["solution"]] = outcome["output_hex"], payload
    checks = puzzle["factory_checks"]
    boolean_modes(checks, "Produced-program checks")
    require(all("relation" not in row for row in checks), "Canonical quote factory must not relabel its relation")
    keys = {(row["environment"], row["backend"], row["optimize_lir"]) for row in checks}
    require(len(checks) == len(keys) and keys == {(environment, *build) for environment in accepted for build in BUILDS}, "Missing or duplicate produced-program checks")
    application_inputs = {serialize(parse(solution)) for solution in ["()", "1", "0x0001", "(1 . 2)"]}
    for row in checks:
        program, payload = accepted[row["environment"]]
        require(row["program_hex"] == program and row["expected_output_hex"] == payload, "Produced program/payload bytes changed or normalized")
        applications = row["application_runs"]
        require(len(applications) == 4 and {serialize(parse(run["solution"])) for run in applications} == application_inputs, "Incomplete second-stage environment coverage")
        for run in applications:
            execution = run["execution"]
            check_execution(execution, "factory second-stage application")
            require(execution["outcome"] == {"status": "accepted", "output_hex": payload}, "Second-stage program did not return the expected raw payload")
            require(type(execution["cost"]) is int and execution["cost"] > 0 and execution["error"] is None, "Missing actual successful application execution record")
    curry_counts = {factory["slug"]: validate_curry_factory(factory, reader) for factory in curry}
    return len(puzzle["cases"]), len(checks), sum(len(row["application_runs"]) for row in checks), curry_counts


def curry_self_test(report):
    """Mutation controls for original standard-curry factories; no process credit."""
    slugs = [puzzle["slug"] for puzzle in report["puzzles"] if puzzle["kind"] == "program_factory" and "module_identity" not in puzzle]
    if not slugs:
        return 0
    def padded_case(p):
        return next(case for case in p["cases"] if case["solution"] == "(0x0001 0x0002)")
    def rejected_case(p):
        return next(case for case in p["cases"] if case["native"]["status"] == "rejected")
    mutations = [
        ("relabeled relation", lambda p: p["factory_checks"][0].update(relation="quote")),
        ("missing relation", lambda p: p["factory_checks"][0].pop("relation")),
        ("canonical identity claim", lambda p: p.update(module_identity={"upstream_hex": "", "upstream_tree_hash": "", "comparisons": []})),
        ("wrong returned program", lambda p: p["factory_checks"][0].update(program_hex="01")),
        ("changed expected program", lambda p: p["factory_checks"][0].update(expected_output_hex="01")),
        ("normalized padded native program", lambda p: padded_case(p)["native"].update(output_hex=padded_case(p)["native"]["output_hex"].replace("820001", "01"))),
        ("accepted malformed environment", lambda p: rejected_case(p).update(native={"status": "accepted", "output_hex": "80"})),
        ("missing application expectation", lambda p: p["factory_checks"][0]["application_runs"][0].pop("expected_outcome")),
        ("application differs from expectation", lambda p: p["factory_checks"][0]["application_runs"][0].update(expected_outcome={"status": "rejected"})),
        ("missing application input", lambda p: p["factory_checks"][0]["application_runs"].pop()),
        ("missing produced program", lambda p: p["factory_checks"].pop()),
        ("missing backend", lambda p: p["artifacts"].pop()),
        ("false direct ledger claim", lambda p: p["simulator"].append({"name": "invented", "passed": True, "scope": "ledger"})),
        ("renamed vector", lambda p: p["cases"][0].update(label="renamed")),
    ]
    for slug in slugs:
        original = next(puzzle for puzzle in report["puzzles"] if puzzle["slug"] == slug)
        original_wire = json.dumps(original, sort_keys=True, separators=(",", ":"))
        for label, mutate in mutations:
            changed = copy.deepcopy(report)
            mutate(next(puzzle for puzzle in changed["puzzles"] if puzzle["slug"] == slug))
            require(json.dumps(next(puzzle for puzzle in changed["puzzles"] if puzzle["slug"] == slug), sort_keys=True, separators=(",", ":")) != original_wire,
                    f"No-op curry mutation: {label}")
            try:
                validate(changed)
            except (ValueError, KeyError):
                continue
            raise ValueError(f"Curry factory mutation was not rejected: {slug}: {label}")
    return len(mutations) * len(slugs)


def self_test(report):
    def mode_rows(puzzle, collection):
        return {
            "artifacts": puzzle["artifacts"],
            "identity comparisons": puzzle["module_identity"]["comparisons"],
            "factory executions": puzzle["cases"][0]["runs"],
            "produced-program checks": puzzle["factory_checks"],
        }[collection]

    def numeric_mode(puzzle, collection, value):
        rows = mode_rows(puzzle, collection)
        row = next(row for row in rows if row["optimize_lir"] is bool(value))
        row["optimize_lir"] = value

    def lose_optimized_identity(puzzle):
        original = next(item for item in puzzle["artifacts"] if item["backend"] == "rust_mir" and not item["optimize_lir"])
        replacement = copy.deepcopy(original)
        replacement["optimize_lir"] = True
        index = next(i for i, item in enumerate(puzzle["artifacts"]) if item["backend"] == "rust_mir" and item["optimize_lir"])
        puzzle["artifacts"][index] = replacement
        comparison = next(row for row in puzzle["module_identity"]["comparisons"] if row["backend"] == "rust_mir" and row["optimize_lir"])
        comparison.update(serialized_bytes_equal=False, tree_hash_equal=False)

    false_metadata = json.loads(read_source("puzzles/p2-conditions/puzzle.json"))
    false_metadata["provenance"]["upstream"]["git_blob_sha1"] = "0" * 40
    mutations = [
        ("changed original source", None, {"puzzles/p2-conditions/reference.clsp": b"(mod () (q . 1))\n"}),
        ("changed license", None, {LICENSE: b"changed license"}),
        ("changed published artifact", None, {ARTIFACT: b"01\n"}),
        ("matching false manifest/report blob metadata", lambda p: p["provenance"]["upstream"].update(git_blob_sha1="0" * 40), {"puzzles/p2-conditions/puzzle.json": json.dumps(false_metadata).encode()}),
        ("missing backend", lambda p: p["artifacts"].pop(), {}),
        ("false module identity", lambda p: p["module_identity"]["comparisons"][0].update(serialized_bytes_equal=not p["module_identity"]["comparisons"][0]["serialized_bytes_equal"]), {}),
        ("lost optimized Rust canonical identity with consistent flags", lose_optimized_identity, {}),
        ("missing produced program", lambda p: p["factory_checks"].pop(), {}),
        ("wrong returned program", lambda p: p["factory_checks"][0].update(program_hex="01"), {}),
        ("normalized padded payload", lambda p: next(row for row in p["factory_checks"] if row["environment"] == "(0x0001)").update(expected_output_hex="01"), {}),
        ("missing second-stage input", lambda p: p["factory_checks"][0]["application_runs"].pop(), {}),
        ("wrong second-stage output", lambda p: p["factory_checks"][0]["application_runs"][0]["execution"].update(outcome={"status":"rejected"}), {}),
        ("false direct ledger claim", lambda p: p["simulator"].append({"name":"invented", "passed":True,"scope":"ledger"}), {}),
    ]
    def rejected_execution(puzzle):
        return next(run["execution"] for case in puzzle["cases"] for run in case["runs"]
                    if run["execution"]["outcome"]["status"] == "rejected")

    mutations += [
        ("missing typed rejection", lambda p: rejected_execution(p).pop("failure"), {}),
        ("unknown rejection code", lambda p: rejected_execution(p)["failure"].update(code="future_code"), {}),
        ("cost limit disguised as rejection", lambda p: rejected_execution(p).update(error="Raise(spoofed)", failure={"kind":"resource","code":"cost_exceeded"}), {}),
        ("infrastructure disguised as rejection", lambda p: rejected_execution(p).update(failure={"kind":"infrastructure","code":"internal_error"}), {}),
        ("accepted application with hidden failure", lambda p: p["factory_checks"][0]["application_runs"][0]["execution"].update(failure={"kind":"resource","code":"cost_exceeded"}), {}),
    ]
    for value in (0, 1, 0.0, 1.0):
        mutations.append((f"numeric validated flag {value!r}", lambda p, value=value: p.update(validated=value), {}))
    for collection in ("artifacts", "identity comparisons", "factory executions", "produced-program checks"):
        for value in (0, 1, 0.0, 1.0):
            mutations.append((f"{collection}: numeric {type(value).__name__} mode {value!r}",
                              lambda p, collection=collection, value=value: numeric_mode(p, collection, value), {}))
    original = next(puzzle for puzzle in report["puzzles"] if puzzle["slug"] == "p2-conditions")
    # Compare serialized JSON, not Python container equality: replacing a
    # Boolean with its numerically equal int/float changes the report's wire.
    original_wire = json.dumps(original, sort_keys=True, separators=(",", ":"))
    for label, mutate, files in mutations:
        changed = copy.deepcopy(report)
        puzzle = next(puzzle for puzzle in changed["puzzles"] if puzzle["slug"] == "p2-conditions")
        if mutate:
            mutate(puzzle)
        require(json.dumps(puzzle, sort_keys=True, separators=(",", ":")) != original_wire
                or any(read_source(path) != contents for path, contents in files.items()),
                f"No-op mutation: {label}")
        try:
            validate(changed, lambda path: files[path] if path in files else read_source(path))
        except (ValueError, KeyError):
            continue
        raise ValueError(f"Mutation was not rejected: {label}")
    print(f"PASS: {len(mutations)} canonical factory provenance/identity/raw-payload/replay mutation controls")
    print(f"PASS: {curry_self_test(report)} standard-curry factory mutation controls")


