const AMOUNT: u64 = 1_000;
const DEADLINE: u64 = 100;
const RECIPIENT: [u8; 32] = [0x42; 32];
const REFUND: [u8; 32] = [0x43; 32];
const CLAIM_INTENT: &[u8; 32] = b"chialisp-oxide/boomerang/claim:1";
const WRONG_INTENT: [u8; 32] = [0xcd; 32];
// Independent receipt spelling of chia-sdk-types 0.36.0 TESTNET11's
// AGG_SIG_ME domain. Actual signatures are generated by the SDK signer.
const ADDITIONAL_DATA: &str = "37a90eb5185a9c4439a91ddc98bbadce7b4feba060d50116a067de66bf236615";
const BUILDS: [(&str, bool); 5] = [
    ("rust_mir", false),
    ("rust_mir", true),
    ("chialisp", true),
    ("rue_source", false),
    ("rue_source", true),
];

#[derive(Serialize)]
pub struct CoinRecord {
    pub coin_id: String,
    pub parent_coin_id: String,
    pub puzzle_hash: String,
    pub amount: u64,
}
impl From<Coin> for CoinRecord {
    fn from(coin: Coin) -> Self {
        Self {
            coin_id: hex::encode(coin.coin_id()),
            parent_coin_id: hex::encode(coin.parent_coin_info),
            puzzle_hash: hex::encode(coin.puzzle_hash),
            amount: coin.amount,
        }
    }
}

