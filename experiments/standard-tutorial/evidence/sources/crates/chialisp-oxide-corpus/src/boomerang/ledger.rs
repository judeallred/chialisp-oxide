#[derive(Clone)]
struct Terms {
    key: [u8; 48],
    recipient: [u8; 32],
    refund: [u8; 32],
    amount: u64,
    deadline: u64,
}
impl Terms {
    fn encode(&self) -> Result<Vec<u8>> {
        serialized(&format!(
            "(0x{} 0x{} 0x{} {} {})",
            hex::encode(self.key),
            hex::encode(self.recipient),
            hex::encode(self.refund),
            self.amount,
            self.deadline,
        ))
    }

    fn conditions(&self, claim: bool) -> Result<Vec<u8>> {
        // Independent condition-wire oracle, not the SDK constructors used by
        // the actual Rust policy. Ordering and the optional tail are exact.
        let opcode = if claim { 85 } else { 81 };
        let destination = if claim { self.recipient } else { self.refund };
        let signature = if claim {
            format!(
                " (50 0x{} 0x{})",
                hex::encode(self.key),
                hex::encode(CLAIM_INTENT)
            )
        } else {
            String::new()
        };
        serialized(&format!(
            "(({opcode} {}) (73 {}) (51 0x{} {}){signature})",
            self.deadline,
            self.amount,
            hex::encode(destination),
            self.amount,
        ))
    }
}

fn serialized(text: &str) -> Result<Vec<u8>> {
    let mut a = Allocator::new();
    let node = rue_clvm::assemble(&mut a, text)?;
    Ok(node_to_bytes(&a, node)?)
}

fn environment(argument: &[u8], solution: &str) -> Result<String> {
    let mut a = Allocator::new();
    let argument = node_from_bytes(&mut a, argument)?;
    let solution = rue_clvm::assemble(&mut a, solution)?;
    let environment = a.new_pair(argument, solution)?;
    Ok(rue_clvm::disassemble_value(&a, environment))
}

fn state(simulator: &Simulator, coin: Coin) -> Result<State> {
    let input = simulator
        .coin_state(coin.coin_id())
        .context("missing boomerang input state")?;
    let mut children = simulator
        .children(coin.coin_id())
        .into_iter()
        .map(|child| CoinRecord::from(child.coin))
        .collect::<Vec<_>>();
    children.sort_by(|a, b| a.coin_id.cmp(&b.coin_id));
    Ok(State {
        height: simulator.height(),
        next_timestamp: simulator.next_timestamp(),
        created_height: input.created_height,
        spent_height: input.spent_height,
        children,
    })
}

#[derive(Clone, Copy)]
enum Expected {
    Accepted([u8; 32]),
    // This closed allowlist is scoped to boomerang's instance protocol.
    // WrongPuzzleHash/runtime umbrellas do not widen the shared protocol.
    Consensus(ErrorCode),
    RuntimeUmbrella,
}
#[derive(Clone, Copy)]
enum Signing {
    Empty,
    Recipient,
    WrongKey,
    WrongIntent,
    OtherCoin,
}
impl Signing {
    fn name(self) -> &'static str {
        match self {
            Self::Empty => "empty",
            Self::Recipient => "recipient",
            Self::WrongKey => "wrong_key",
            Self::WrongIntent => "wrong_intent",
            Self::OtherCoin => "other_coin",
        }
    }
}

struct Input<'a> {
    label: &'static str,
    timestamp: u64,
    terms: &'a Terms,
    reveal: &'a [u8],
    solution: &'a str,
    claim: Option<bool>,
    signing: Signing,
    expected: Expected,
}
struct Case {
    label: &'static str,
    timestamp: u64,
    amount: u64,
    claim: bool,
    signing: Signing,
    expected: Expected,
}
struct Runner<'a> {
    instance: &'a [u8],
    terms: &'a Terms,
    owner: &'a SecretKey,
    wrong_key: &'a SecretKey,
}

fn exact_list(a: &Allocator, mut node: NodePtr, count: usize) -> Result<Vec<NodePtr>> {
    let mut fields = Vec::with_capacity(count);
    for _ in 0..count {
        let SExp::Pair(first, rest) = a.sexp(node) else {
            anyhow::bail!("signer-only claim condition fixture is not the exact proper list");
        };
        fields.push(first);
        node = rest;
    }
    ensure!(
        matches!(a.sexp(node), SExp::Atom) && a.atom(node).as_ref().is_empty(),
        "signer-only claim condition fixture has an extra/improper tail"
    );
    Ok(fields)
}
fn list(a: &mut Allocator, fields: &[NodePtr]) -> Result<NodePtr> {
    let mut rest = NodePtr::NIL;
    for first in fields.iter().rev() {
        rest = a.new_pair(*first, rest)?;
    }
    Ok(rest)
}

/// Mutate only the intent in this particular build's executed claim output,
/// then quote that data for signer extraction. This reveal is never submitted:
/// the transaction still executes the original committed instance.
fn wrong_intent_reveal(output_hex: &str) -> Result<Vec<u8>> {
    let mut a = Allocator::new();
    let output = node_from_bytes(&mut a, &hex::decode(output_hex)?)?;
    let mut conditions = exact_list(&a, output, 4)?;
    let mut signature = exact_list(&a, conditions[3], 3)?;
    ensure!(
        matches!(a.sexp(signature[2]), SExp::Atom) && a.atom(signature[2]).as_ref() == CLAIM_INTENT,
        "wrong-intent control requires the actual original claim intent"
    );
    signature[2] = a.new_atom(&WRONG_INTENT)?;
    conditions[3] = list(&mut a, &signature)?;
    let conditions = list(&mut a, &conditions)?;
    let quote = a.new_atom(&[1])?;
    let reveal = a.new_pair(quote, conditions)?;
    Ok(node_to_bytes(&a, reveal)?)
}

fn signature_context(key: &SecretKey, intent: &[u8], coin: Coin) -> SignatureContext {
    let intent_hex = hex::encode(intent);
    let coin_id = hex::encode(coin.coin_id());
    SignatureContext {
        public_key: hex::encode(key.public_key().to_bytes()),
        message_hex: format!("{intent_hex}{coin_id}{ADDITIONAL_DATA}"),
        intent_hex,
        coin_id,
        additional_data: ADDITIONAL_DATA,
    }
}
fn signature_origin(coin: Coin, reveal: &[u8], solution: &str) -> Result<SignatureOrigin> {
    Ok(SignatureOrigin {
        coin: coin.into(),
        reveal_hex: hex::encode(reveal),
        reveal_tree_hash: hex::encode(puzzle_hash(reveal)?),
        solution: solution.into(),
        solution_hex: hex::encode(serialized(solution)?),
    })
}

impl Runner<'_> {
    fn fresh(&self, case: Case) -> Result<Attempt> {
        let mut simulator = Simulator::new();
        let coin = create_coin(&mut simulator, self.instance, case.amount)?;
        self.attempt(
            &mut simulator,
            coin,
            Input {
                label: case.label,
                timestamp: case.timestamp,
                terms: self.terms,
                reveal: self.instance,
                solution: if case.claim { "(1)" } else { "(())" },
                claim: Some(case.claim),
                signing: case.signing,
                expected: case.expected,
            },
        )
    }

    fn attempt(&self, simulator: &mut Simulator, coin: Coin, input: Input<'_>) -> Result<Attempt> {
        simulator.set_next_timestamp(input.timestamp)?;
        let argument = input.terms.encode()?;
        let solution = serialized(input.solution)?;
        let vm_021 = execute(input.reveal, input.solution, MAX_COST)?;
        ensure!(
            vm_021.outcome != Outcome::Inconclusive,
            "{}: inconclusive boomerang primary VM observation: {vm_021:?}",
            input.label
        );
        let native = crate::expectation("boomerang", &environment(&argument, input.solution)?)?;
        ensure!(
            vm_021.outcome == native,
            "{}: ledger reveal differs from actual native uncurried Rust policy",
            input.label
        );
        if let Some(claim) = input.claim {
            ensure!(
                vm_021.outcome
                    == Outcome::Accepted {
                        output_hex: hex::encode(input.terms.conditions(claim)?)
                    },
                "{}: actual policy changed independent exact condition tree",
                input.label
            );
        } else {
            ensure!(
                matches!(input.expected, Expected::RuntimeUmbrella)
                    && vm_021.outcome == Outcome::Rejected
                    && vm_021
                        .failure
                        .is_some_and(|failure| failure.is_program_rejection()),
                "{}: malformed solution must first have a typed primary VM program rejection: {vm_021:?}",
                input.label
            );
        }
        // Deliberately bypass host puzzle-hash preflight for substituted reveals.
        let spend = CoinSpend::new(coin, program(input.reveal)?, program(&solution)?);
        let spends = std::slice::from_ref(&spend);
        let (signature, signature_context, signature_origin) = match input.signing {
            Signing::Empty => (Signature::default(), None, None),
            Signing::Recipient => (
                sign_transaction(spends, std::slice::from_ref(self.owner))?,
                Some(signature_context(self.owner, CLAIM_INTENT, coin)),
                None,
            ),
            Signing::WrongKey => (
                sign_single_requirement_with_wrong_key(spends, self.wrong_key)?,
                Some(signature_context(self.wrong_key, CLAIM_INTENT, coin)),
                None,
            ),
            Signing::WrongIntent => {
                let Outcome::Accepted { output_hex } = &vm_021.outcome else {
                    anyhow::bail!(
                        "wrong-intent signer fixture requires actual accepted claim output"
                    );
                };
                let reveal = wrong_intent_reveal(output_hex)?;
                let origin = CoinSpend::new(coin, program(&reveal)?, program(&solution)?);
                (
                    sign_transaction(&[origin], std::slice::from_ref(self.owner))?,
                    Some(signature_context(self.owner, &WRONG_INTENT, coin)),
                    Some(signature_origin(coin, &reveal, input.solution)?),
                )
            }
            Signing::OtherCoin => {
                let origin_coin = create_coin(simulator, self.instance, AMOUNT)?;
                ensure!(
                    origin_coin.coin_id() != coin.coin_id(),
                    "other-coin signature must change coin identity"
                );
                let origin =
                    CoinSpend::new(origin_coin, program(input.reveal)?, program(&solution)?);
                (
                    sign_transaction(&[origin], std::slice::from_ref(self.owner))?,
                    Some(signature_context(self.owner, CLAIM_INTENT, origin_coin)),
                    Some(signature_origin(origin_coin, input.reveal, input.solution)?),
                )
            }
        };
        ensure!(
            (signature == Signature::default()) == matches!(input.signing, Signing::Empty),
            "{}: signature control must distinguish an actual nonempty signature from omission",
            input.label
        );
        // Signer fixture coins, if any, are part of the complete rollback snapshot.
        let before_simulator = simulator.clone();
        let before = state(simulator, coin)?;
        let signature_hex = hex::encode(signature.to_bytes());
        let result = simulator.new_transaction(SpendBundle::new(vec![spend], signature));
        let consensus = match (input.expected, result) {
            (Expected::Accepted(destination), Ok(_)) => {
                let children = simulator.children(coin.coin_id());
                ensure!(
                    before.spent_height.is_none() && before.children.is_empty(),
                    "{}: accepted control must begin with an unspent input and no children",
                    input.label
                );
                ensure!(
                    children.len() == 1
                        && children[0].coin.parent_coin_info == coin.coin_id()
                        && children[0].coin.amount == AMOUNT
                        && children[0].coin.puzzle_hash.as_slice() == destination
                        && children[0].spent_height.is_none()
                        && children[0].created_height == Some(before.height),
                    "{}: accepted boomerang changed exact full-amount child",
                    input.label
                );
                ensure!(
                    simulator
                        .coin_state(coin.coin_id())
                        .is_some_and(|state| state.spent_height == Some(before.height)
                            && state.created_height == before.created_height),
                    "{}: accepted boomerang input was not marked spent",
                    input.label
                );
                ensure!(
                    simulator.height() == before.height + 1
                        && simulator.next_timestamp() == input.timestamp + 1,
                    "{}: accepted transaction did not advance the fixture block and clock exactly once",
                    input.label
                );
                ConsensusObservation {
                    status: "accepted",
                    code: None,
                    error: None,
                    semantic_rejection_credit: false,
                }
            }
            (Expected::Consensus(expected), Err(SimulatorError::Validation(actual)))
                if expected == actual =>
            {
                ConsensusObservation {
                    status: "consensus_rejected",
                    code: Some(format!("{actual:?}")),
                    error: Some(format!("Validation({actual:?})")),
                    semantic_rejection_credit: true,
                }
            }
            (
                Expected::RuntimeUmbrella,
                Err(SimulatorError::Validation(ErrorCode::GeneratorRuntimeError)),
            ) => ConsensusObservation {
                status: "runtime_umbrella",
                code: Some("GeneratorRuntimeError".into()),
                error: Some("Validation(GeneratorRuntimeError)".into()),
                semantic_rejection_credit: false,
            },
            (_, actual) => anyhow::bail!(
                "boomerang ledger {} had unexpected submission outcome: {actual:?}",
                input.label
            ),
        };
        let full_state_unchanged = *simulator == before_simulator;
        ensure!(
            (consensus.status == "accepted") != full_state_unchanged,
            "{}: boomerang transition or full SDK rollback failed",
            input.label
        );
        Ok(Attempt {
            label: input.label,
            timestamp: input.timestamp,
            argument_hex: hex::encode(argument),
            coin: coin.into(),
            reveal_hex: hex::encode(input.reveal),
            reveal_tree_hash: hex::encode(puzzle_hash(input.reveal)?),
            solution: input.solution.into(),
            solution_hex: hex::encode(solution),
            signature_kind: input.signing.name(),
            signature_hex,
            signature_context,
            signature_origin,
            vm_021,
            consensus,
            before,
            after: state(simulator, coin)?,
            full_state_unchanged,
        })
    }
}

pub(super) fn validate(
    programs: &[(&str, bool, Vec<u8>)],
    examples: &[curried::Example],
) -> Result<Vec<Comparison>> {
    ensure!(
        programs
            .iter()
            .map(|(b, o, _)| (*b, *o))
            .collect::<Vec<_>>()
            == BUILDS,
        "boomerang ledger requires the five ordered builds"
    );
    let [example] = examples else {
        anyhow::bail!("boomerang ledger requires one actual curried example");
    };
    ensure!(
        example.label == "public_demo_payment" && example.instances.len() == BUILDS.len(),
        "boomerang ledger requires exactly the fixed public demonstration instances"
    );
    let owner = SecretKey::from_seed(&[0x17; 32]);
    let wrong_key = SecretKey::from_seed(&[0x18; 32]);
    let terms = Terms {
        key: owner.public_key().to_bytes(),
        recipient: RECIPIENT,
        refund: REFUND,
        amount: AMOUNT,
        deadline: DEADLINE,
    };
    let argument = terms.encode()?;
    ensure!(
        hex::encode(&argument) == example.argument_hex
            && serialized(&example.argument)? == argument,
        "boomerang ledger supports only its independently reconstructed demo Terms"
    );
    let mut comparisons = Vec::with_capacity(BUILDS.len());
    for ((backend, optimize, module), instance_record) in programs.iter().zip(&example.instances) {
        let instance = hex::decode(&instance_record.artifact.clvm_hex)?;
        let module_hash = artifact(backend, *optimize, module)?.tree_hash;
        let instance_hash = hex::encode(puzzle_hash(&instance)?);
        ensure!(
            instance_record.backend == *backend
                && instance_record.optimize_lir == *optimize
                && instance_record.module_tree_hash == module_hash
                && instance_record.artifact.tree_hash == instance_hash
                && curried::standard_form(module, &argument)? == instance,
            "boomerang ledger instance does not match its exact ordered module and Terms"
        );
        let runner = Runner {
            instance: &instance,
            terms: &terms,
            owner: &owner,
            wrong_key: &wrong_key,
        };
        let mut attempts = Vec::with_capacity(29);
        let cases = [
            Case {
                label: "claim_before_deadline",
                timestamp: 99,
                amount: AMOUNT,
                claim: true,
                signing: Signing::Recipient,
                expected: Expected::Accepted(RECIPIENT),
            },
            Case {
                label: "refund_at_deadline",
                timestamp: 100,
                amount: AMOUNT,
                claim: false,
                signing: Signing::Empty,
                expected: Expected::Accepted(REFUND),
            },
            Case {
                label: "refund_after_deadline",
                timestamp: 101,
                amount: AMOUNT,
                claim: false,
                signing: Signing::Empty,
                expected: Expected::Accepted(REFUND),
            },
            Case {
                label: "claim_at_deadline",
                timestamp: 100,
                amount: AMOUNT,
                claim: true,
                signing: Signing::Recipient,
                expected: Expected::Consensus(ErrorCode::AssertBeforeSecondsAbsoluteFailed),
            },
            Case {
                label: "claim_after_deadline",
                timestamp: 101,
                amount: AMOUNT,
                claim: true,
                signing: Signing::Recipient,
                expected: Expected::Consensus(ErrorCode::AssertBeforeSecondsAbsoluteFailed),
            },
            Case {
                label: "refund_before_deadline",
                timestamp: 99,
                amount: AMOUNT,
                claim: false,
                signing: Signing::Empty,
                expected: Expected::Consensus(ErrorCode::AssertSecondsAbsoluteFailed),
            },
            Case {
                label: "claim_missing_signature",
                timestamp: 99,
                amount: AMOUNT,
                claim: true,
                signing: Signing::Empty,
                expected: Expected::Consensus(ErrorCode::BadAggregateSignature),
            },
            Case {
                label: "claim_wrong_key",
                timestamp: 99,
                amount: AMOUNT,
                claim: true,
                signing: Signing::WrongKey,
                expected: Expected::Consensus(ErrorCode::BadAggregateSignature),
            },
            Case {
                label: "claim_wrong_intent",
                timestamp: 99,
                amount: AMOUNT,
                claim: true,
                signing: Signing::WrongIntent,
                expected: Expected::Consensus(ErrorCode::BadAggregateSignature),
            },
            Case {
                label: "claim_other_coin_signature",
                timestamp: 99,
                amount: AMOUNT,
                claim: true,
                signing: Signing::OtherCoin,
                expected: Expected::Consensus(ErrorCode::BadAggregateSignature),
            },
            Case {
                label: "refund_amount_too_small",
                timestamp: 100,
                amount: AMOUNT - 1,
                claim: false,
                signing: Signing::Empty,
                expected: Expected::Consensus(ErrorCode::AssertMyAmountFailed),
            },
            Case {
                label: "refund_amount_too_large",
                timestamp: 100,
                amount: AMOUNT + 1,
                claim: false,
                signing: Signing::Empty,
                expected: Expected::Consensus(ErrorCode::AssertMyAmountFailed),
            },
        ];
        for case in cases {
            attempts.push(runner.fresh(case)?);
        }
        for (label, field) in [
            ("substituted_recipient_key", 0),
            ("substituted_recipient", 1),
            ("substituted_refund", 2),
            ("substituted_amount", 3),
            ("substituted_deadline", 4),
        ] {
            let mut substituted = terms.clone();
            match field {
                0 => substituted.key = wrong_key.public_key().to_bytes(),
                1 => substituted.recipient = [0x44; 32],
                2 => substituted.refund = [0x45; 32],
                3 => substituted.amount = AMOUNT + 1,
                4 => substituted.deadline = DEADLINE + 1,
                _ => unreachable!(),
            }
            let reveal = curried::standard_form(module, &substituted.encode()?)?;
            ensure!(
                puzzle_hash(&reveal)? != puzzle_hash(&instance)?,
                "substituted Terms must change commitment"
            );
            let mut simulator = Simulator::new();
            let coin = create_coin(&mut simulator, &instance, AMOUNT)?;
            attempts.push(runner.attempt(
                &mut simulator,
                coin,
                Input {
                    label,
                    timestamp: 101,
                    terms: &substituted,
                    reveal: &reveal,
                    solution: "(())",
                    claim: Some(false),
                    signing: Signing::Empty,
                    expected: Expected::Consensus(ErrorCode::WrongPuzzleHash),
                },
            )?);
        }
        for (setup, replay, timestamp, claim, destination) in [
            ("refund_replay_setup", "refund_replay", 100, false, REFUND),
            (
                "claim_then_refund_setup",
                "claim_then_refund",
                99,
                true,
                RECIPIENT,
            ),
        ] {
            let mut simulator = Simulator::new();
            let coin = create_coin(&mut simulator, &instance, AMOUNT)?;
            attempts.push(runner.attempt(
                &mut simulator,
                coin,
                Input {
                    label: setup,
                    timestamp,
                    terms: &terms,
                    reveal: &instance,
                    solution: if claim { "(1)" } else { "(())" },
                    claim: Some(claim),
                    signing: if claim {
                        Signing::Recipient
                    } else {
                        Signing::Empty
                    },
                    expected: Expected::Accepted(destination),
                },
            )?);
            attempts.push(runner.attempt(
                &mut simulator,
                coin,
                Input {
                    label: replay,
                    timestamp: timestamp + 1,
                    terms: &terms,
                    reveal: &instance,
                    solution: "(())",
                    claim: Some(false),
                    signing: Signing::Empty,
                    expected: Expected::Consensus(ErrorCode::DoubleSpend),
                },
            )?);
        }
        for (label, solution) in [
            ("malformed_empty_solution", "()"),
            ("malformed_atom_solution", "1"),
            ("malformed_bool_two", "(2)"),
            ("malformed_zero_byte", "(0x00)"),
            ("malformed_padded_true", "(0x0001)"),
            ("malformed_pair_bool", "((1))"),
            ("malformed_extra_argument", "(1 0)"),
            ("malformed_improper_tail", "(1 . 2)"),
        ] {
            let mut simulator = Simulator::new();
            let coin = create_coin(&mut simulator, &instance, AMOUNT)?;
            attempts.push(runner.attempt(
                &mut simulator,
                coin,
                Input {
                    label,
                    timestamp: 100,
                    terms: &terms,
                    reveal: &instance,
                    solution,
                    claim: None,
                    signing: Signing::Empty,
                    expected: Expected::RuntimeUmbrella,
                },
            )?);
        }
        ensure!(
            attempts.len() == 29,
            "boomerang transaction matrix must remain explicit and complete"
        );
        comparisons.push(Comparison {
            backend: (*backend).into(),
            optimize_lir: *optimize,
            instance_label: example.label.clone(),
            module_tree_hash: module_hash,
            instance_tree_hash: instance_hash,
            simulator: SIMULATOR_VERSION,
            consensus: CONSENSUS_VERSION,
            vm: VM_VERSION,
            network: NETWORK,
            transaction_attempts: attempts.len(),
            attempts,
        });
    }
    Ok(comparisons)
}
